package research

import (
	"fmt"
	"math"
	"math/big"
	"sort"
	"strconv"
	"strings"
)

// RiskTargetInput supplies the already computed risk cap, flags and effective
// price to the offline final sizing step. It does not evaluate risk conditions.
type RiskTargetInput struct {
	TargetQty       float64  `json:"target_qty"`
	TargetLeverage  float64  `json:"target_leverage"`
	CurrentPosition float64  `json:"current_position"`
	Equity          float64  `json:"equity"`
	LeverageCap     float64  `json:"leverage_cap"`
	Price           float64  `json:"price"`
	ReduceOnly      bool     `json:"reduce_only"`
	ReasonCodes     []string `json:"reason_codes"`
	Flags           []string `json:"flags"`
}

type RiskTargetResult struct {
	TargetQty      float64  `json:"target_qty"`
	TargetLeverage float64  `json:"target_leverage"`
	ReduceOnly     bool     `json:"reduce_only"`
	ReasonCodes    []string `json:"reason_codes"`
	Flags          []string `json:"flags"`
}

// ClampRiskTarget implements offline risk target contract v2. Unlike the
// historical Python v1 reference, quantity (six decimals) and the lesser of
// requested leverage and its cap (four decimals) are quantized toward zero.
// Leverage is an independently capped intent, not a value derived from quantity.
// Quantization never increases exposure or crosses a reduce-only position. This
// is not a complete risk overlay or order authorization.
func ClampRiskTarget(in RiskTargetInput) (RiskTargetResult, error) {
	for _, value := range []float64{in.TargetQty, in.TargetLeverage, in.CurrentPosition, in.Equity, in.LeverageCap, in.Price} {
		if !sizingFinite(value) {
			return RiskTargetResult{}, fmt.Errorf("risk target inputs must be finite")
		}
	}
	if in.Equity < 0 || in.LeverageCap < 0 || in.TargetLeverage < 0 || in.Price < 1e-9 {
		return RiskTargetResult{}, fmt.Errorf("invalid risk target equity, leverage or effective price")
	}
	notional := in.Equity * in.LeverageCap
	if !sizingFinite(notional) {
		return RiskTargetResult{}, fmt.Errorf("risk target notional overflow")
	}
	limit := notional / in.Price
	if !sizingFinite(limit) {
		return RiskTargetResult{}, fmt.Errorf("risk target quantity limit overflow")
	}
	// Derive the cap from exact binary64 inputs and round downward. The
	// ordinary product and quotient above retain their existing overflow guards.
	exactNotional := new(big.Rat).Mul(new(big.Rat).SetFloat64(in.Equity), new(big.Rat).SetFloat64(in.LeverageCap))
	exactLimit := new(big.Rat).Quo(exactNotional, new(big.Rat).SetFloat64(in.Price))
	limit, exact := exactLimit.Float64()
	if math.IsInf(limit, 1) {
		limit = math.MaxFloat64
	} else if !exact && new(big.Rat).SetFloat64(limit).Cmp(exactLimit) > 0 {
		limit = math.Nextafter(limit, 0)
	}
	qty := math.Max(-limit, math.Min(limit, in.TargetQty))
	flags := append([]string{}, in.Flags...)
	if in.ReduceOnly {
		if in.CurrentPosition > 0 {
			qty = math.Max(0, math.Min(qty, in.CurrentPosition))
		} else if in.CurrentPosition < 0 {
			qty = math.Min(0, math.Max(qty, in.CurrentPosition))
		} else {
			qty = 0
		}
		if qty != in.TargetQty {
			flags = append(flags, "REDUCE_ONLY_BLOCK_ADD")
		}
	}
	reasons := sortedRiskStrings(append(append([]string{}, in.ReasonCodes...), flags...))
	flags = sortedRiskStrings(flags)
	if len(flags) == 0 {
		flags = []string{"OK"}
	}
	return RiskTargetResult{riskQuantizeTowardZero(qty, 1e6), riskQuantizeTowardZero(math.Min(in.TargetLeverage, in.LeverageCap), 1e4), in.ReduceOnly, reasons, flags}, nil
}

// Quantize the shortest round-trippable decimal representation. This preserves
// already-quantized values across calls and avoids overflow in float scaling.
func riskQuantizeTowardZero(value, scale float64) float64 {
	text := strconv.FormatFloat(math.Abs(value), 'f', -1, 64)
	precision := 6
	if scale == 1e4 {
		precision = 4
	}
	point := strings.IndexByte(text, '.')
	if point < 0 || len(text)-point-1 <= precision {
		return value
	}
	text = text[:point+1+precision]
	quantized, err := strconv.ParseFloat(text, 64)
	if err != nil {
		panic(err) // text is generated by strconv.FormatFloat
	}
	return math.Copysign(quantized, value)
}

func sortedRiskStrings(values []string) []string {
	sort.Strings(values)
	result := make([]string, 0, len(values))
	for _, value := range values {
		if len(result) == 0 || result[len(result)-1] != value {
			result = append(result, value)
		}
	}
	return result
}
